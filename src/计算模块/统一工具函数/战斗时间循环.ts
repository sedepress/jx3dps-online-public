import { 循环详情, 循环技能详情 } from '@/@types/循环'
import { 问水诀Excel战斗时间数据, 问水诀Excel战斗时间选项 } from './问水诀Excel战斗时间数据'

const 保留数量精度 = (值: number) => Number(值.toFixed(12))

const 获取技能数量计算基准 = (循环详情: 循环详情) => {
  return 循环详情.技能数量计算时间 || 循环详情.战斗时间
}

const 是否默认战斗时间 = (循环详情: 循环详情, 战斗时间: 问水诀Excel战斗时间选项) => {
  if (typeof 战斗时间 !== 'number') {
    return false
  }
  const 默认战斗时间 = Math.round(获取技能数量计算基准(循环详情))
  return 战斗时间 === 默认战斗时间
}

const 缩放技能增益列表 = (技能: 循环技能详情, 比例: number) => {
  return 技能.技能增益列表?.map((增益) => ({
    ...增益,
    增益技能数:
      typeof 增益.增益技能数 === 'number' ? 保留数量精度(增益.增益技能数 * 比例) : 增益.增益技能数,
  }))
}

const 缩放动态技能数量 = (技能: 循环技能详情, 比例: number) => {
  if (!技能.动态技能数量) {
    return undefined
  }
  return {
    ...技能.动态技能数量,
    基础数量: 保留数量精度(技能.动态技能数量.基础数量 * 比例),
  }
}

const 缩放技能数量 = (技能: 循环技能详情, 比例: number): 循环技能详情 => {
  return {
    ...技能,
    技能数量: 保留数量精度(技能.技能数量 * 比例),
    动态技能数量: 缩放动态技能数量(技能, 比例),
    技能增益列表: 缩放技能增益列表(技能, 比例),
  }
}

const 获取覆盖率 = (
  循环详情: 循环详情,
  战斗时间: number,
  覆盖率覆盖?: { [key: string]: number },
) => {
  if (!循环详情.覆盖率) {
    return undefined
  }
  const 覆盖率 = { ...循环详情.覆盖率, ...覆盖率覆盖 }
  if (覆盖率.风特效腰坠 && typeof 覆盖率覆盖?.风特效腰坠 !== 'number') {
    覆盖率.风特效腰坠 = 30 / 战斗时间
  }
  return 覆盖率
}

const 获取增益覆盖率 = (
  循环详情: 循环详情,
  战斗时间: number,
  增益覆盖率覆盖?: { [key: string]: number },
) => {
  if (!循环详情.增益覆盖率) {
    return undefined
  }
  const 增益覆盖率 = { ...循环详情.增益覆盖率, ...增益覆盖率覆盖 }
  if (增益覆盖率.号令三军 && typeof 增益覆盖率覆盖?.号令三军 !== 'number') {
    增益覆盖率.号令三军 = (45 / 战斗时间) * 100
  }
  return 增益覆盖率
}

const 替换技能数量 = (技能: 循环技能详情, 技能数量?: number): 循环技能详情 => {
  if (typeof 技能数量 !== 'number') {
    return 技能
  }

  return {
    ...技能,
    技能数量,
    动态技能数量: 技能.动态技能数量
      ? {
          ...技能.动态技能数量,
          基础数量: 技能数量,
        }
      : undefined,
    技能增益列表: 技能.技能增益列表?.map((增益) => ({
      ...增益,
      增益技能数: 技能数量,
    })),
  }
}

const 获取Excel技能数量计算时间 = (
  战斗时间: 问水诀Excel战斗时间选项,
  秒伤计算时间: number,
  技能数量计算时间?: number,
) => {
  if (typeof 技能数量计算时间 === 'number') {
    return 技能数量计算时间
  }
  return typeof 战斗时间 === 'number' ? 战斗时间 : 秒伤计算时间
}

const 根据Excel战斗时间生成循环详情 = (循环详情: 循环详情, 战斗时间: 问水诀Excel战斗时间选项) => {
  const 数据Key = 循环详情.Excel战斗时间数据Key
  const 战斗时间数据 = 数据Key ? 问水诀Excel战斗时间数据[数据Key]?.[战斗时间] : undefined

  if (!战斗时间数据) {
    return undefined
  }

  const 技能数量计算时间 = 获取Excel技能数量计算时间(
    战斗时间,
    战斗时间数据.秒伤计算时间,
    战斗时间数据.技能数量计算时间,
  )

  return {
    ...循环详情,
    战斗时间: 战斗时间数据.秒伤计算时间,
    秒伤计算时间: 战斗时间数据.秒伤计算时间,
    技能数量计算时间,
    追加技能数量: 战斗时间数据.追加技能数量,
    覆盖率: 获取覆盖率(循环详情, 技能数量计算时间, 战斗时间数据.覆盖率),
    增益覆盖率: 获取增益覆盖率(循环详情, 技能数量计算时间, 战斗时间数据.增益覆盖率),
    技能详情: 循环详情.技能详情.map((技能, index) =>
      替换技能数量(技能, 战斗时间数据.技能数量列表[index]),
    ),
  }
}

export const 根据战斗时间生成循环详情 = (
  循环详情: 循环详情,
  战斗时间?: 问水诀Excel战斗时间选项,
) => {
  if (!战斗时间 || !循环详情.支持战斗时间覆盖) {
    return 循环详情
  }
  if (是否默认战斗时间(循环详情, 战斗时间)) {
    return 循环详情
  }

  const Excel循环详情 = 根据Excel战斗时间生成循环详情(循环详情, 战斗时间)
  if (Excel循环详情) {
    return Excel循环详情
  }

  if (typeof 战斗时间 !== 'number') {
    return 循环详情
  }

  const 基准时间 = 获取技能数量计算基准(循环详情)
  const 比例 = 战斗时间 / 基准时间
  return {
    ...循环详情,
    战斗时间,
    秒伤计算时间: 战斗时间,
    技能数量计算时间: 战斗时间,
    覆盖率: 获取覆盖率(循环详情, 战斗时间),
    增益覆盖率: 获取增益覆盖率(循环详情, 战斗时间),
    技能详情: 循环详情.技能详情.map((技能) => 缩放技能数量(技能, 比例)),
  }
}
