import { describe, expect, it, jest } from '@jest/globals'
import 根据表单选项获取装备信息 from './index'

jest.mock('../根据装备信息获取基础属性', () => (装备信息) => 装备信息)

jest.mock('@/数据/数据工具/获取当前数据', () => () => ({
  装备数据: {
    帽子: [
      { id: 35300, 装备品级: 35300 },
      { id: 41400, 装备品级: 41400 },
      { id: 43100, 装备品级: 43100 },
    ],
  },
}))

describe('根据表单选项获取装备信息的大附魔品级校验', () => {
  it('清除英雄品装备上的普通大附魔', () => {
    const 结果 = 根据表单选项获取装备信息({
      _1: { id: 41400, 装备部位: '帽子' },
      大附魔_伤帽: 1,
    })

    expect(结果.装备增益.大附魔_伤帽).toBeUndefined()
  })

  it('保留低品装备上的英雄大附魔', () => {
    const 结果 = 根据表单选项获取装备信息({
      _1: { id: 35300, 装备部位: '帽子' },
      大附魔_伤帽: 2,
    })

    expect(结果.装备增益.大附魔_伤帽).toBe(2)
  })

  it('清除超过英雄大附魔上限的档位', () => {
    const 结果 = 根据表单选项获取装备信息({
      _1: { id: 43100, 装备部位: '帽子' },
      大附魔_伤帽: 2,
    })

    expect(结果.装备增益.大附魔_伤帽).toBeUndefined()
  })
})
