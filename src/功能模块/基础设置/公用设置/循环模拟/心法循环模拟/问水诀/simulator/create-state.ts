import { 每秒郭氏帧 } from '../rules/constants'
import { 创建问水状态参数, 问水模拟状态 } from '../types'

const 最短战斗秒数 = 1
const 最长战斗秒数 = 600

const 校验战斗秒数 = (战斗秒数: number) => {
  if (!Number.isInteger(战斗秒数) || 战斗秒数 < 最短战斗秒数 || 战斗秒数 > 最长战斗秒数) {
    throw new Error('战斗时长必须是 1-600 的整数秒')
  }
}

export const 创建问水起手状态 = ({
  战斗秒数,
  加速值,
  网络延迟,
}: 创建问水状态参数): 问水模拟状态 => {
  校验战斗秒数(战斗秒数)
  return {
    当前帧: 0,
    结束帧: 战斗秒数 * 每秒郭氏帧,
    姿态: '轻剑',
    剑气: 0,
    加速值,
    网络延迟,
    分支概率: 1,
    断潮可用: false,
    自身Buff: {},
    目标Buff: {},
    团队增益: {},
    技能CD: {},
    GCD: { 公共: 0, 自身: {} },
    待生效事件: [],
    伤害事件: [],
    技能记录: [],
  }
}
