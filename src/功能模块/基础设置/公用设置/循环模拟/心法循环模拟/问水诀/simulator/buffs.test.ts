import { describe, expect, it } from '@jest/globals'
import { 创建问水起手状态 } from './create-state'
import { 执行动作 } from './engine'
import { 推进到帧 } from './time'

describe('问水诀职业 Buff', () => {
  it('夕照命中后添加 15 秒雾锁，后续技能携带雾锁签名', () => {
    const state = {
      ...创建问水起手状态({ 战斗秒数: 30, 加速值: 0, 网络延迟: 0 }),
      姿态: '重剑' as const,
      剑气: 100,
    }
    const 夕照 = 执行动作(state, '夕照雷峰', { 奇穴: ['雾锁'] })
    const 命中后 = 推进到帧(夕照.状态, 夕照.状态.技能记录[0].命中帧)
    const 云飞 = 执行动作({ ...命中后, 当前帧: 命中后.GCD.公共, 剑气: 100 }, '云飞玉皇')
    const 云飞命中后 = 推进到帧(云飞.状态, 云飞.状态.技能记录.at(-1)?.命中帧 || 0)

    expect(命中后.自身Buff.雾锁.结束帧).toBe(夕照.状态.技能记录[0].命中帧 + 240)
    expect(云飞命中后.伤害事件.find((item) => item.技能名称 === '云飞玉皇')?.增益签名).toContain(
      '雾锁',
    )
  })

  it('非快照技能命中前雾锁过期时不保留雾锁签名', () => {
    const state = {
      ...创建问水起手状态({ 战斗秒数: 30, 加速值: 0, 网络延迟: 0 }),
      姿态: '重剑' as const,
      剑气: 100,
      自身Buff: { 雾锁: { 层数: 1, 获得帧: 0, 结束帧: 5 } },
    }
    const 云飞 = 执行动作(state, '云飞玉皇')
    const 命中后 = 推进到帧(云飞.状态, 云飞.状态.技能记录[0].命中帧)

    expect(命中后.伤害事件.find((item) => item.技能名称 === '云飞玉皇')?.增益签名).not.toContain(
      '雾锁',
    )
  })

  it('层云只进入风来签名，怜光进入所有重剑伤害签名', () => {
    const state = {
      ...创建问水起手状态({ 战斗秒数: 30, 加速值: 0, 网络延迟: 0 }),
      姿态: '重剑' as const,
      剑气: 100,
    }
    const 风来 = 执行动作(state, '风来吴山', { 奇穴: ['层云', '怜光'] })

    expect(风来.状态.待生效事件[0].增益签名).toEqual(['怜光'])
  })

  it('碧归层数只被下一次其余灵峰剑式消耗一层', () => {
    const state = {
      ...创建问水起手状态({ 战斗秒数: 30, 加速值: 0, 网络延迟: 0 }),
      姿态: '重剑' as const,
      剑气: 100,
      自身Buff: { 碧归: { 层数: 2, 获得帧: 0, 结束帧: 144 } },
    }
    const 云飞 = 执行动作(state, '云飞玉皇', { 奇穴: ['碧归'] })

    expect(云飞.状态.自身Buff.碧归.层数).toBe(1)
    expect(云飞.状态.待生效事件.find((item) => item.技能名称 === '云飞玉皇')?.增益签名).toContain(
      '碧归',
    )
  })

  it('轻剑技能不携带也不消耗碧归', () => {
    const state = {
      ...创建问水起手状态({ 战斗秒数: 30, 加速值: 0, 网络延迟: 0 }),
      自身Buff: { 碧归: { 层数: 2, 获得帧: 0, 结束帧: 144 } },
    }
    const 听雷 = 执行动作(state, '听雷-轻', { 奇穴: ['碧归'] })

    expect(听雷.状态.自身Buff.碧归.层数).toBe(2)
    expect(
      听雷.状态.待生效事件.find((item) => item.技能名称 === '听雷-轻')?.增益签名,
    ).not.toContain('碧归')
  })

  it('碧归由主动作决定云飞二段和山倾继承范围', () => {
    const state = {
      ...创建问水起手状态({ 战斗秒数: 30, 加速值: 0, 网络延迟: 0 }),
      姿态: '重剑' as const,
      剑气: 100,
      自身Buff: { 碧归: { 层数: 3, 获得帧: 0, 结束帧: 144 } },
    }
    const 云飞 = 执行动作(state, '云飞玉皇', { 奇穴: ['碧归'], 触发玉山揽云: true })
    const 鹤归 = 执行动作(state, '鹤归孤山', { 奇穴: ['碧归', '山倾'] })

    expect(
      云飞.状态.待生效事件.find((item) => item.技能名称 === '云飞玉皇·二段')?.增益签名,
    ).toContain('碧归')
    expect(
      云飞.状态.待生效事件.find((item) => item.技能名称 === '玉山揽云')?.增益签名,
    ).not.toContain('碧归')
    expect(
      鹤归.状态.待生效事件.find((item) => item.技能名称 === '鹤归孤山·山倾')?.增益签名,
    ).toContain('碧归')
  })
})
