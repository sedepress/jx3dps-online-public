import { describe, expect, it } from '@jest/globals'
import { 团队增益轴类型 } from '@/@types/团队增益'
import { 创建问水起手状态 } from './create-state'
import { 创建带增益签名的伤害事件, 添加团队增益轴事件, 获取当前团队增益签名 } from './team-buffs'
import { 执行同帧, 推进到帧 } from './time'

const 测试增益轴: 团队增益轴类型 = {
  朝圣: {
    是否启用快照: true,
    释放时间点: [4],
    平均间隔: -1,
    持续时间: 4,
  },
}

describe('问水诀团队增益时间轴', () => {
  it('在开始帧前为空，窗口内生效，结束帧动作后移除', () => {
    const 初始状态 = 创建问水起手状态({ 战斗秒数: 2, 加速值: 0, 网络延迟: 0 })
    const 带事件状态 = 添加团队增益轴事件(初始状态, 测试增益轴)
    const 开始前 = 推进到帧(带事件状态, 3)
    let 开始帧签名: string[] = []

    const 窗口内 = 执行同帧(开始前, 4, (state) => {
      开始帧签名 = 获取当前团队增益签名(state)
      return state
    })
    let 结束帧签名: string[] = []
    const 窗口结束 = 执行同帧(窗口内, 8, (state) => {
      结束帧签名 = 获取当前团队增益签名(state)
      return state
    })

    expect(获取当前团队增益签名(开始前)).toEqual([])
    expect(开始帧签名).toEqual(['朝圣_快照'])
    expect(结束帧签名).toEqual(['朝圣_快照'])
    expect(获取当前团队增益签名(窗口结束)).toEqual([])
  })

  it('创建伤害事件时固化快照，增益结束后不再变化', () => {
    const 初始状态 = 创建问水起手状态({ 战斗秒数: 2, 加速值: 0, 网络延迟: 0 })
    const 带事件状态 = 添加团队增益轴事件(初始状态, 测试增益轴)
    const 窗口内 = 推进到帧(带事件状态, 5)
    const 伤害事件 = 创建带增益签名的伤害事件(窗口内, {
      技能名称: '九皋鹤野·落剑',
      命中帧: 10,
      序号: 100,
      是否快照: true,
    })
    const 结算后 = 推进到帧({ ...窗口内, 待生效事件: 窗口内.待生效事件.concat(伤害事件) }, 10)

    expect(获取当前团队增益签名(结算后)).toEqual([])
    expect(结算后.伤害事件[0]).toMatchObject({
      技能名称: '九皋鹤野·落剑',
      增益签名: ['朝圣_快照'],
      快照签名: ['朝圣_快照'],
    })
  })
})
