const 获取斩岳循环计算结果 = async (增益配置?: { 增益启用?: boolean; 增益数据?: any }) => {
  const { 初始化心法数据 } = require('src/数据/数据工具/获取当前数据')
  await 初始化心法数据('问水诀')

  const { 秒伤计算 } = require('src/计算模块/计算函数')
  const 叠锋意斩岳循环 = 心法配置.计算循环.find((循环) => 循环.名称 === '叠锋意斩岳循环')
  if (!叠锋意斩岳循环) {
    throw new Error('缺少叠锋意斩岳循环')
  }
  const 斩岳循环详情 = 叠锋意斩岳循环.循环详情[0]

  const state = {
    data: {
      网络延迟: 1,
      装备信息: 心法配置.默认数据.配装,
      当前输出计算目标名称: '134级木桩',
      增益启用: 增益配置?.增益启用 || false,
      增益数据: 增益配置?.增益数据 || { 阵眼: '', 小吃: [], 团队增益: [] },
      当前奇穴信息: 叠锋意斩岳循环.奇穴,
      当前秘籍信息: 心法配置.默认数据.秘籍,
      当前计算循环名称: 叠锋意斩岳循环.名称,
      自定义循环列表: [],
      团队增益轴: {},
    },
  }

  const 计算结果 = 秒伤计算({
    更新计算循环详情: 斩岳循环详情,
    更新循环技能列表: 斩岳循环详情.技能详情,
    更新计算时间: 斩岳循环详情.战斗时间,
    更新奇穴数据: 叠锋意斩岳循环.奇穴,
    更新增益启用: 增益配置?.增益启用 || false,
    更新增益数据: 增益配置?.增益数据,
    计算技能详情: true,
  })(undefined, () => state)

  return { 计算结果 }
}

